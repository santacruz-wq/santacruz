  static String obtenerDescripcion({
    required String nombre,
    required String idioma,
    String? descripcionOriginal,
  }) {
    final lista = descripciones[nombre.trim()];

    if (lista == null) {
      return descripcionOriginal ?? '';
    }

    final indice = _idiomas.indexOf(idioma);

    if (indice < 0 || indice >= lista.length) {
      return lista.first;
    }

    return lista[indice];
  }
