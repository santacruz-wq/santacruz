  static String normalizarIdioma(String idioma) {
    final codigo = idioma.toLowerCase().trim().replaceAll('_', '-');

    if (codigo.startsWith('zh')) return 'zh';
    if (codigo.startsWith('pt')) return 'pt';

    return codigo.split('-').first;
  }

  static String normalizarTexto(String texto) {
    return texto
        .trim()
        .toLowerCase()
        .replaceAll('á', 'a')
        .replaceAll('é', 'e')
        .replaceAll('í', 'i')
        .replaceAll('ó', 'o')
        .replaceAll('ú', 'u');
  }

  static String obtenerNombre({
    required String clave,
    required String idioma,
    String? nombreOriginal,
  }) {
    final idiomaNormalizado = normalizarIdioma(idioma);

    return productosPorIdioma[idiomaNormalizado]?[clave] ??
        productosPorIdioma['es']?[clave] ??
        nombreOriginal ??
        clave;
  }

  static String obtenerDescripcion({
    required String clave,
    required String idioma,
    String? descripcionOriginal,
  }) {
    final indice = clavesDescripciones.indexOf(clave);

    if (indice == -1) {
      return descripcionOriginal ?? '';
    }

    final idiomaNormalizado = normalizarIdioma(idioma);
    final traducciones = descripcionesPorIdioma[idiomaNormalizado];

    if (traducciones != null && indice < traducciones.length) {
      return traducciones[indice];
    }

    final espanol = descripcionesPorIdioma['es']!;
    return indice < espanol.length
        ? espanol[indice]
        : descripcionOriginal ?? '';
  }

  static String? obtenerClavePorCodigo(String codigo) {
    final codigoNormalizado = codigo.trim().toUpperCase();

    for (final entrada in codigosProductos.entries) {
      if (entrada.value.toUpperCase() == codigoNormalizado) {
        return entrada.key;
      }
    }

    return null;
  }

  static String obtenerCategoria({
    required String nombre,
    required String idioma,
  }) {
    final idiomaNormalizado = normalizarIdioma(idioma);
    final nombreNormalizado = normalizarTexto(nombre);
    final categoriasEspanol = categoriasPorIdioma['es']!;

    for (final categoria in categoriasEspanol.keys) {
      if (normalizarTexto(categoria) == nombreNormalizado) {
        return categoriasPorIdioma[idiomaNormalizado]?[categoria] ??
            categoria;
      }
    }

    return nombre;
  }
